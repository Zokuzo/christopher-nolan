// Reading the generated src/Root.tsx: find a project's <Composition> between `nolan:begin/end <slug>`
// markers (any comment style) and evaluate its inline `defaultProps` literal as Studio wrote it.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { compIdFor, genRoot } from '../../src/lib/root-gen.ts';
import { join } from 'node:path';
import { projectDir, ROOT } from './paths.ts';

export const ROOT_TSX = join(ROOT, 'src', 'Root.tsx');

export const compId = compIdFor; // one definition shared with Root generation

export const readRoot = (): string => (existsSync(ROOT_TSX) ? readFileSync(ROOT_TSX, 'utf8') : '');

const esc = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Slugs that have a marked block in the Root source.
export const rootSlugs = (src: string): string[] =>
	[...src.matchAll(/nolan:begin ([a-z0-9][a-z0-9-]*)/g)].map((m) => m[1]);

// Index just past the bracket that closes the one at `open`, skipping strings and comments.
const matchBracket = (src: string, open: number): number => {
	let depth = 0;
	for (let i = open; i < src.length; i++) {
		const c = src[i];
		if (c === '"' || c === "'" || c === '`') {
			for (i++; i < src.length && src[i] !== c; i++) if (src[i] === '\\') i++;
		} else if (c === '/' && src[i + 1] === '/') {
			i = src.indexOf('\n', i);
			if (i < 0) return -1;
		} else if (c === '/' && src[i + 1] === '*') {
			i = src.indexOf('*/', i + 2) + 1;
			if (i <= 0) return -1;
		} else if (c === '{' || c === '[' || c === '(') depth++;
		else if (c === '}' || c === ']' || c === ')') {
			if (--depth === 0) return i + 1;
		}
	}
	return -1;
};

// Source text of the defaultProps object literal for `slug`, or null when absent.
export const extractDefaultProps = (src: string, slug: string): string | null => {
	const begin = new RegExp(`nolan:begin ${esc(slug)}(?![a-z0-9-])`).exec(src);
	const end = new RegExp(`nolan:end ${esc(slug)}(?![a-z0-9-])`).exec(src);
	if (!begin || !end || end.index < begin.index) return null;
	const block = src.slice(begin.index, end.index);
	const at = block.search(/defaultProps\s*=\s*\{/);
	if (at < 0) return null;
	const open = block.indexOf('{', at); // JSX expression container
	const close = matchBracket(block, open);
	if (close < 0) return null;
	return block.slice(open + 1, close - 1).trim();
};

// Studio writes TS (`'fade' as const`, `staticFile("x")`, `new Date("...")`): drop the TS-only parts,
// then evaluate. The file is local and generated by us/Studio, hence trusted.
export const evalLiteral = (literal: string): unknown => {
	const js = literal.replace(/('(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`)|\bas\s+const\b/g, (m, s: string | undefined) => s ?? '');
	return new Function('staticFile', `return (${js});`)((p: string) => p);
};

// Remove every `_*` key at any depth (derived props from calculateMetadata).
export const stripPrivate = (v: unknown): unknown =>
	Array.isArray(v) ? v.map(stripPrivate)
	: v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, stripPrivate(x)]))
	: v;

// Studio-side props for `slug`: undefined if Root has no block for it. Throws on an unparsable literal.
export const rootProps = (slug: string, src = readRoot()): unknown => {
	const literal = extractDefaultProps(src, slug);
	if (literal === null) return undefined;
	try { return stripPrivate(evalLiteral(literal)); }
	catch (e) { throw new Error(`src/Root.tsx: cannot evaluate defaultProps of "${slug}": ${(e as Error).message}`); }
};

// What `nolan studio` last wrote into Root for a slug: tells Studio edits (Root ≠ base) from agent edits
// (scenario.json ≠ base), so neither side silently overwrites the other.
export const basePath = (slug: string): string => join(projectDir(slug), '.studio-base.json');
export const readBase = (slug: string): unknown =>
	existsSync(basePath(slug)) ? JSON.parse(readFileSync(basePath(slug), 'utf8')) : undefined;
export const writeBase = (slug: string, scenario: unknown): void =>
	writeFileSync(basePath(slug), JSON.stringify(scenario, null, 2) + '\n');

// Render/stills never depend on what Studio's Root currently shows: bundle a throwaway entry that
// registers only this composition (props come from --props anyway). Removed afterwards.
export const withRenderEntry = async <T>(slug: string, scenario: object, fn: (entry: string) => Promise<T>): Promise<T> => {
	const entry = join(ROOT, 'src', `.nolan-render-${slug}.tsx`);
	writeFileSync(entry, `${genRoot([{ slug, compId: compId(slug), scenario }])}\nimport { registerRoot } from 'remotion';\nregisterRoot(RemotionRoot);\n`);
	try { return await fn(entry); }
	finally { rmSync(entry, { force: true }); }
};
