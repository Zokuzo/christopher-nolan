// nolan setup — vendor CC0 @remotion/sfx sounds, generate our own riser/impact/pop/ding + fallback music bed,
// write public/sfx/index.json (+ credits.json) and public/music/index.json, install headless Chrome, create config dir.
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, extname, join } from 'node:path';
import * as remotionSfx from '@remotion/sfx';
import type { CommandContext } from '../nolan.ts';
import { parseArgs } from '../lib/args.ts';
import { info, next, ok, warn } from '../lib/log.ts';
import { CACHE_DIR, PUBLIC_DIR, configDir } from '../lib/paths.ts';
import { remotion } from '../lib/proc.ts';
import { ffmpeg, resolveTool } from '../lib/ffmpeg.ts';
import { download, normalizeMusic, normalizeSfx } from '../audio/media.ts';

const SFX_DIR = join(PUBLIC_DIR, 'sfx');
const MUSIC_DIR = join(PUBLIC_DIR, 'music');
const CC0 = { license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' };
const OURS = { creator: 'christopher-nolan', license: 'CC0 (generated by christopher-nolan)', licenseUrl: CC0.licenseUrl, sourceUrl: 'https://github.com/Zokuzo/christopher-nolan', provider: 'bundled' };

// Allowlist of @remotion/sfx sounds, credits from remotion.dev/docs/sfx/<name> (all CC0, checked 2026-09-30).
// `ding` is left out on purpose: its page says it is "not explicitly released under a free license"; we generate our own.
const VENDOR: Record<string, { exp: keyof typeof remotionSfx; title: string; creator: string; sourceUrl: string }> = {
	whoosh: { exp: 'whoosh', title: 'Woosh', creator: '1bob', sourceUrl: 'https://freesound.org/s/831936/' },
	whip: { exp: 'whip', title: 'SWSH_Badminton Racquet_Recording_01_JW Audio', creator: 'JW_Audio', sourceUrl: 'https://freesound.org/s/838766/' },
	click: { exp: 'mouseClick', title: 'Mouse Click Sound', creator: 'Pixeliota', sourceUrl: 'https://freesound.org/s/678248/' },
	switch: { exp: 'uiSwitch', title: 'UI Audio - Switch 35', creator: 'kenney.nl', sourceUrl: 'https://kenney.nl' },
	'page-turn': { exp: 'pageTurn', title: 'Draw Knife 1', creator: 'kenney.nl', sourceUrl: 'https://kenney.nl' },
	shutter: { exp: 'shutterModern', title: 'DSLR Shutter fast 006', creator: 'ristooooo1', sourceUrl: 'https://freesound.org/s/539136/' },
};

// Synth recipes (system ffmpeg lavfi). Chirps use phase integrals so pitch glides are click-free.
const RISER_S = 3;
const chirp = (f0: number) => `sin(2*PI*${f0}*${RISER_S}/log(8)*(pow(8,t/${RISER_S})-1))*pow(t/${RISER_S},2)*(0.75+0.25*sin(2*PI*(2*t+1.5*t*t)))`;
const SYNTH: Record<string, { title: string; graph: string }> = {
	riser: {
		title: 'Riser (3 s)',
		graph: `aevalsrc=exprs='0.5*${chirp(150)}|0.5*${chirp(151)}':s=48000:d=${RISER_S}[a];`
			+ `anoisesrc=d=${RISER_S}:c=pink:r=48000:a=0.6,highpass=f=800,volume='pow(t/${RISER_S},3)':eval=frame,aformat=channel_layouts=stereo[n];`
			+ `[a][n]amix=inputs=2:weights='1 0.8':normalize=0,aecho=0.8:0.6:60|110:0.3|0.2`,
	},
	impact: {
		title: 'Cinematic impact',
		graph: `aevalsrc=exprs='0.9*sin(2*PI*(42*t+140*(1-exp(-14*t))/14))*exp(-2.2*t)*min(1,t*800)':s=48000:d=2.2,aformat=channel_layouts=stereo[b];`
			+ `anoisesrc=d=2.2:c=brown:r=48000:a=1,lowpass=f=1800,volume='exp(-14*t)':eval=frame,aformat=channel_layouts=stereo[n];`
			+ `[b][n]amix=inputs=2:weights='1 0.7':normalize=0,aecho=0.8:0.5:90|170:0.35|0.2`,
	},
	pop: {
		title: 'Pop',
		graph: `aevalsrc=exprs='0.9*sin(2*PI*(260*t+900*(1-exp(-45*t))/45))*exp(-32*t)*min(1,t*1500)':s=48000:d=0.18,aformat=channel_layouts=stereo`,
	},
	ding: {
		title: 'Bell ding',
		graph: `aevalsrc=exprs='min(1,t*400)*(0.5*sin(2*PI*1318.5*t)*exp(-3*t)+0.25*sin(2*PI*2637*t)*exp(-5*t)+0.15*sin(2*PI*3639*t)*exp(-8*t)+0.08*sin(2*PI*7120*t)*exp(-14*t))':s=48000:d=1.8,`
			+ 'aformat=channel_layouts=stereo,aecho=0.8:0.4:40|75:0.25|0.15',
	},
};

// 60 s ambient drone that loops seamlessly: every frequency and LFO completes whole cycles in 60 s.
// A1 sub + high shimmer + slow crossfade Am (A2 E3 C4 E4) <-> F (F2 C3 A3 F4), R channel detuned +0.25 Hz for width.
const BED_S = 60;
const bedChannel = (detune: number): string => {
	const am = 'cos(2*PI*t/60)*0.5+0.5';
	const f = '(1-(cos(2*PI*t/60)*0.5+0.5))';
	const hzs = (hz: number): string => String(Number((hz + detune).toFixed(3)));
	const voice = (hz: number, amp: number, weight: string, lfo: number, phase: number): string =>
		`${amp}*(${weight})*(0.65+0.35*sin(2*PI*${lfo}*t/60+${phase}))*(sin(2*PI*${hzs(hz)}*t)+0.25*sin(2*PI*${hzs(2 * hz)}*t))`;
	const sum = [
		`0.12*(0.8+0.2*sin(2*PI*t*3/60))*sin(2*PI*${hzs(55)}*t)`,
		voice(110, 0.13, am, 5, 0), voice(164.8, 0.09, am, 7, 1), voice(261.6, 0.05, am, 4, 2), voice(329.6, 0.035, am, 9, 3),
		voice(87.3, 0.13, f, 6, 0.5), voice(130.8, 0.09, f, 8, 1.5), voice(220, 0.05, f, 5, 2.5), voice(349.2, 0.035, f, 11, 3.5),
		voice(659.2, 0.012, '1', 13, 0.7), voice(880, 0.008, '1', 17, 2.1), // high shimmer
	].map((x) => `(${x})`).join('+');
	return `(${sum})*(0.85+0.15*sin(2*PI*12*t/60))`; // slow tremolo (0.2 Hz)
};
const BED_GRAPH = `aevalsrc=exprs='(${bedChannel(0)})|(${bedChannel(0.25)})':s=48000:d=${BED_S}[pad];`
	+ `anoisesrc=d=${BED_S}:c=pink:r=48000:a=0.5,lowpass=f=1400,volume='0.09*(0.6+0.4*sin(2*PI*3*t/60))':eval=frame,aformat=channel_layouts=stereo[air];`
	+ `[pad][air]amix=inputs=2:normalize=0,aecho=0.8:0.7:180|310:0.3|0.22,highpass=f=35,lowpass=f=6000`;

const synth = async (graph: string, wav: string): Promise<void> => {
	const r = await ffmpeg(['-hide_banner', '-y', '-filter_complex', graph, '-ar', '48000', wav]);
	if (r.code !== 0) throw new Error(r.stderr.trim().split('\n').pop() ?? 'ffmpeg failed');
};

export async function run(args: string[], _ctx: CommandContext): Promise<void> {
	const { flags } = parseArgs(args, ['force', 'skip-browser']);
	const force = flags.force === true;
	mkdirSync(configDir(), { recursive: true });
	mkdirSync(SFX_DIR, { recursive: true });
	mkdirSync(MUSIC_DIR, { recursive: true });
	ok(`config dir ${configDir()}`);

	const credits: Record<string, object> = {};
	for (const [name, v] of Object.entries(VENDOR)) {
		const out = join(SFX_DIR, `${name}.wav`);
		credits[name] = { title: v.title, creator: v.creator, ...CC0, attribution: `"${v.title}" by ${v.creator} (CC0 1.0, via @remotion/sfx)`, sourceUrl: v.sourceUrl, provider: 'remotion-sfx' };
		if (existsSync(out) && !force) continue;
		try {
			const file = await download(remotionSfx[v.exp] as string);
			if (extname(file) !== '.wav') throw new Error(`expected wav, got ${extname(file)}`);
			copyFileSync(file, out);
			info(`  vendored sfx/${name}.wav`);
		} catch (e) { warn(`sfx ${name}: ${(e as Error).message}`); }
	}

	// Remotion's bundled ffmpeg has no lavfi sources: generation needs a system ffmpeg.
	const canSynth = resolveTool('ffmpeg').source === 'system';
	const gen = join(CACHE_DIR, 'gen');
	mkdirSync(gen, { recursive: true });
	for (const [name, s] of Object.entries(SYNTH)) {
		const out = join(SFX_DIR, `${name}.mp3`);
		credits[name] = { title: s.title, ...OURS, attribution: `"${s.title}" generated by christopher-nolan (CC0)` };
		if (existsSync(out) && !force) continue;
		if (!canSynth) { warn(`sfx ${name}: needs a system ffmpeg to generate (install ffmpeg, then setup --force)`); continue; }
		try {
			await synth(s.graph, join(gen, `${name}.wav`));
			await normalizeSfx(join(gen, `${name}.wav`), out);
			info(`  generated sfx/${name}.mp3`);
		} catch (e) { warn(`sfx ${name}: ${(e as Error).message}`); }
	}

	const bed = join(MUSIC_DIR, 'fallback-bed.mp3');
	if ((!existsSync(bed) || force) && canSynth) {
		try {
			await synth(BED_GRAPH, join(gen, 'fallback-bed.wav'));
			await normalizeMusic(join(gen, 'fallback-bed.wav'), bed, undefined, 128);
			info('  generated music/fallback-bed.mp3');
		} catch (e) { warn(`music bed: ${(e as Error).message}`); }
	} else if (!existsSync(bed)) warn('music bed: needs a system ffmpeg to generate');

	// Manifests reflect what is actually on disk (Mix resolves sfx by name through index.json).
	const index: Record<string, string> = {};
	for (const f of readdirSync(SFX_DIR).filter((f) => /\.(wav|mp3)$/.test(f)).sort()) index[basename(f, extname(f))] = `sfx/${f}`;
	writeFileSync(join(SFX_DIR, 'index.json'), JSON.stringify(index, null, 2) + '\n');
	writeFileSync(join(SFX_DIR, 'credits.json'), JSON.stringify(Object.fromEntries(Object.entries(credits).filter(([n]) => index[n])), null, 2) + '\n');
	const music = existsSync(bed)
		? [{ id: 'fallback-bed', file: 'music/fallback-bed.mp3', title: 'Fallback Bed (ambient drone, 60 s loop)', mood: ['ambient', 'cinematic', 'calm'], ...OURS, attribution: '"Fallback Bed" generated by christopher-nolan (CC0)' }]
		: [];
	writeFileSync(join(MUSIC_DIR, 'index.json'), JSON.stringify(music, null, 2) + '\n');
	ok(`sfx: ${Object.keys(index).join(', ')} → public/sfx/index.json; music beds: ${music.length}`);

	if (flags['skip-browser'] !== true) {
		const r = await remotion(['browser', 'ensure']);
		if (r.code === 0) ok('headless Chrome ready'); else warn('remotion browser ensure failed: retry with node node_modules/@remotion/cli/remotion-cli.js browser ensure');
	}
	next('node cli/nolan.ts doctor');
}
