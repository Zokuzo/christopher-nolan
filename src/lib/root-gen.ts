// Generates src/Root.tsx (pure; used by `nolan studio`). Each composition sits between
// `// nolan:begin <slug>` and `// nolan:end <slug>` lines; defaultProps is an inline object
// literal (required for Studio's save-to-code), which `nolan sync` reads back.
export type RootEntry = { slug: string; compId: string; scenario: unknown };

// Remotion composition ids allow only letters, digits and dashes.
export const compIdFor = (slug: string): string => slug.replace(/[^a-zA-Z0-9-]/g, '-').replace(/^-+|-+$/g, '') || 'video';

const indent = (text: string, tabs: string) => text.split('\n').map((l, i) => (i === 0 ? l : tabs + l)).join('\n');

export const genRoot = (entries: RootEntry[]): string => {
	const blocks = entries.map(({ slug, compId, scenario }) => {
		const props = { ...(scenario as Record<string, unknown>) };
		for (const k of Object.keys(props)) if (k.startsWith('_')) delete props[k];
		return [
			`\t\t\t// nolan:begin ${slug}`,
			`\t\t\t<Composition`,
			`\t\t\t\tkey=${JSON.stringify(compId)}`,
			`\t\t\t\tid=${JSON.stringify(compId)}`,
			`\t\t\t\tcomponent={Video}`,
			`\t\t\t\tschema={ScenarioSchema}`,
			`\t\t\t\tcalculateMetadata={calculateMetadata}`,
			`\t\t\t\tdefaultProps={${indent(JSON.stringify(props, null, '\t'), '\t\t\t\t')}}`,
			`\t\t\t/>,`,
			`\t\t\t// nolan:end ${slug}`,
		].join('\n');
	});
	return `// GENERATED by \`nolan studio\`. Edit props in the Studio Props panel (then save) or in projects/<slug>/scenario.json.
import { Composition } from 'remotion';
import { Video } from './Video.tsx';
import { ScenarioSchema } from './schema.ts';
import { calculateMetadata } from './calculate-metadata.ts';

export const RemotionRoot: React.FC = () => (
	<>
		{[
${blocks.join('\n')}
		]}
	</>
);
`;
};
